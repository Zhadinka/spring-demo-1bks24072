-- ШАГ 2. Схема данных (таблицы, связи, ограничения целостности).
-- Выполнять от postgres, подключившись к БД lab_db:
--   psql -U postgres -d lab_db -f db/02_schema.sql
-- Таблицы принадлежат postgres; приложение подключается другим пользователем (lab_app).


-- Заказчик проб (в коде - сущность User; users, т.к. "user" - зарезервированное слово).
CREATE TABLE users (
    id    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name  VARCHAR(255) NOT NULL,
    email VARCHAR(255),
    CONSTRAINT ck_users_name_not_blank CHECK (btrim(name) <> '')
);
-- e-mail уникален без учёта регистра; NULL допускается (у заказчика может не быть e-mail).
CREATE UNIQUE INDEX ux_users_email_lower ON users (lower(email));

-- Методика анализа: допустимый материал, диапазон значений, максимальный разброс.
CREATE TABLE analysis_methods (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name             VARCHAR(255)     NOT NULL,
    allowed_material VARCHAR(100)     NOT NULL,
    min_value        DOUBLE PRECISION NOT NULL,
    max_value        DOUBLE PRECISION NOT NULL,
    max_spread       DOUBLE PRECISION NOT NULL,
    CONSTRAINT ck_methods_name_not_blank     CHECK (btrim(name) <> ''),
    CONSTRAINT ck_methods_material_not_blank CHECK (btrim(allowed_material) <> ''),
    CONSTRAINT ck_methods_range              CHECK (min_value <= max_value),
    CONSTRAINT ck_methods_spread             CHECK (max_spread >= 0)
);
CREATE UNIQUE INDEX ux_methods_name_lower ON analysis_methods (lower(name));

-- Проба: принадлежит заказчику; удаление заказчика удаляет его пробы.
CREATE TABLE samples (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    material    VARCHAR(100) NOT NULL,
    customer_id BIGINT       NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    received_at TIMESTAMPTZ  NOT NULL,
    status      VARCHAR(20)  NOT NULL,
    CONSTRAINT ck_samples_material_not_blank CHECK (btrim(material) <> ''),
    CONSTRAINT ck_samples_status CHECK (status IN ('RECEIVED', 'IN_PROGRESS', 'COMPLETED', 'REJECTED'))
);
CREATE INDEX ix_samples_customer ON samples (customer_id);

-- Исследование = проба + методика (связь многие-ко-многим с собственными атрибутами).
-- Удаление пробы или методики удаляет её исследования.
CREATE TABLE analyses (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sample_id     BIGINT      NOT NULL REFERENCES samples (id)          ON DELETE CASCADE,
    method_id     BIGINT      NOT NULL REFERENCES analysis_methods (id) ON DELETE CASCADE,
    status        VARCHAR(20) NOT NULL,
    average_value DOUBLE PRECISION,
    CONSTRAINT ck_analyses_status CHECK (status IN ('IN_PROGRESS', 'COMPLETED', 'CANCELLED')),
    -- одна и та же методика не назначается одной пробе дважды
    CONSTRAINT ux_analyses_sample_method UNIQUE (sample_id, method_id),
    -- завершённое исследование всегда имеет итоговое среднее
    CONSTRAINT ck_analyses_completed_has_average CHECK (status <> 'COMPLETED' OR average_value IS NOT NULL)
);
CREATE INDEX ix_analyses_method ON analyses (method_id);

-- Результат измерения; удаление исследования удаляет его измерения.
CREATE TABLE measurements (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    analysis_id    BIGINT           NOT NULL REFERENCES analyses (id) ON DELETE CASCADE,
    measured_value DOUBLE PRECISION NOT NULL,
    measured_at    TIMESTAMPTZ      NOT NULL,
    confirmed      BOOLEAN          NOT NULL DEFAULT FALSE
);
CREATE INDEX ix_measurements_analysis ON measurements (analysis_id);

