-- ШАГ 5. Таблица учетных записей приложения.
-- Выполнять от владельца таблиц / postgres в БД lab_db:
--   psql -U postgres -d lab_db -f db/05_authentication.sql
-- Учетные записи отделены от users: users остаётся заказчиком предметной области.

CREATE TABLE app_accounts (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email         VARCHAR(255) NOT NULL,
    password_hash VARCHAR(100) NOT NULL,
    account_role  VARCHAR(30) NOT NULL DEFAULT 'CUSTOMER',
    status        VARCHAR(20) NOT NULL DEFAULT 'ACTIVE',
    customer_id   BIGINT UNIQUE REFERENCES users (id) ON DELETE CASCADE,
    CONSTRAINT ck_app_accounts_role
        CHECK (account_role IN ('CUSTOMER', 'LAB_TECHNICIAN', 'ADMIN')),
    CONSTRAINT ck_app_accounts_status
        CHECK (status IN ('ACTIVE', 'LOCKED', 'DISABLED')),
    CONSTRAINT ck_app_accounts_customer
        CHECK (account_role <> 'CUSTOMER' OR customer_id IS NOT NULL)
);

CREATE UNIQUE INDEX ux_app_accounts_email_lower ON app_accounts (lower(email));

-- Явно выдаём только DML и доступ к последовательности.
GRANT SELECT, INSERT, UPDATE, DELETE ON app_accounts TO lab_readwrite;
GRANT USAGE, SELECT ON SEQUENCE app_accounts_id_seq TO lab_readwrite;
